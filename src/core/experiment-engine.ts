/**
 * Select directions to adopt based on user choice.
 */
export function selectDirections(
  projectRoot: string,
  experimentName: string,
  directionIds: string[],
): ExperimentState {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) throw new Error(`Experiment not found: ${experimentName}`);

  state.selectedDirections = directionIds;
  state.notes.push(`Selected directions: ${directionIds.join(', ')}`);

  // Mark directions as adopted/rejected
  for (const dir of state.directions) {
    dir.adopted = directionIds.includes(dir.id);
    if (!dir.adopted && !dir.rejectionReason) {
      dir.rejectionReason = 'Not selected in comparison phase';
    }
  }

  saveExperimentState(projectRoot, state);
  return state;
}

/**
 * Merge selected directions back to the main project.
 * ponytail: merge strategy is controlled copy of designated files
 */
export function adoptImprovements(
  projectRoot: string,
  experimentName: string,
): { adopted: string[]; errors: string[] } {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) throw new Error(`Experiment not found: ${experimentName}`);

  state.phase = 'adopting';
  const adopted: string[] = [];
  const errors: string[] = [];

  for (const directionId of state.selectedDirections) {
    const arm = state.arms.find((a) => a.directionId === directionId);
    if (!arm) {
      errors.push(`Arm for direction ${directionId} not found`);
      continue;
    }

    // Cherry-pick the commit from the experiment branch
    const logResult = spawnSync(
      'git', ['log', arm.branch, '--oneline', '-1'],
      { cwd: projectRoot, encoding: 'utf-8' }
    );

    if (logResult.status !== 0) {
      errors.push(`Failed to adopt ${directionId}: git log failed (status ${logResult.status})`);
      continue;
    }

    const output = (logResult.stdout ?? '').trim();
    if (output) {
      const commitSha = output.split(' ')[0];
      const pickResult = spawnSync('git', ['cherry-pick', commitSha], {
        cwd: projectRoot,
        stdio: 'ignore',
      });
      if (pickResult.status === 0) {
        adopted.push(directionId);
      } else {
        errors.push(`Cherry-pick failed for ${directionId} (${commitSha})`);
      }
    }
  }

  state.mergedBack = adopted.length > 0;
  state.phase = 'converged';
  state.completedAt = now();
  saveExperimentState(projectRoot, state);

  return { adopted, errors };
}

