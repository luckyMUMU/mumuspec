/**
 * Generate improvement directions based on codebase analysis.
 * Scans the source code structure to identify potential improvement areas.
 */
export function generateDirections(
  projectRoot: string,
  config: ExperimentConfig,
): ExperimentDirection[] {
  if (config.manualDirections && config.manualDirections.length > 0) {
    return config.manualDirections.map((d, i) => ({
      id: d.id ?? `dir-${i + 1}`,
      name: d.name ?? `Direction ${i + 1}`,
      description: d.description ?? '',
      category: d.category ?? 'performance',
      riskLevel: d.riskLevel ?? 2,
      affectedFiles: d.affectedFiles ?? [],
      changeSummary: d.changeSummary ?? '',
      expectedBenefit: d.expectedBenefit ?? '',
      adopted: false,
    }));
  }

  return autoGenerateDirections(projectRoot, config);
}

/**
 * Auto-generate improvement directions by analyzing codebase patterns.
 * ponytail: lightweight static analysis, no external LLM dependency
 */
function autoGenerateDirections(
  projectRoot: string,
  config: ExperimentConfig,
): ExperimentDirection[] {
  const directions: ExperimentDirection[] = [];
  const srcDir = resolve(projectRoot, 'src');

  // Analyze source structure
  const modules = analyzeSourceModules(srcDir);
  const fileCount = countSourceFiles(srcDir);
  const avgFileSize = calculateAvgFileSize(srcDir, fileCount);
  const categories = config.focusCategories ?? getDefaultCategories();

  // Direction generation heuristics based on codebase analysis
  // ponytail: each direction targets a specific improvement vector

  // Direction 1: Performance optimization (if large files detected)
  if (avgFileSize > 300) {
    directions.push({
      id: 'dir-perf-1',
      name: 'Performance: Large File Splitting',
      description: 'Identify files exceeding size thresholds and propose modular decomposition',
      category: 'performance',
      riskLevel: 3,
      affectedFiles: findLargeFiles(srcDir, 500),
      changeSummary: 'Split files >500 lines into smaller focused modules',
      expectedBenefit: 'Reduced load times, improved maintainability, better test isolation',
      adopted: false,
    });
  }

  // Direction 2: Error handling enhancement
  directions.push({
    id: 'dir-robust-1',
    name: 'Robustness: Enhanced Error Context',
    description: 'Add contextual information to error messages for faster debugging',
    category: 'robustness',
    riskLevel: 1,
    affectedFiles: findFilesWithErrorHandling(srcDir),
    changeSummary: 'Enrich error messages with contextual data (file, line, nearby state)',
    expectedBenefit: 'Faster debugging, better user experience during errors',
    adopted: false,
  });

  // Direction 3: CLI UX improvement
  if (modules.includes('cli')) {
    directions.push({
      id: 'dir-ux-1',
      name: 'Usability: Interactive Prompts',
      description: 'Add interactive confirmation prompts for destructive operations',
      category: 'usability',
      riskLevel: 2,
      affectedFiles: ['src/cli/commands/change.ts', 'src/cli/commands/state.ts'],
      changeSummary: 'Add --yes/-y flag support and interactive confirmations',
      expectedBenefit: 'Reduced accidental deletions, better user confidence',
      adopted: false,
    });
  }

  // Direction 4: Test coverage improvement
  directions.push({
    id: 'dir-test-1',
    name: 'Maintainability: Test Pattern Extraction',
    description: 'Extract common test patterns into reusable test utilities',
    category: 'maintainability',
    riskLevel: 2,
    affectedFiles: findTestFilesWithPatterns(srcDir),
    changeSummary: 'Create shared test fixtures and assertion helpers',
    expectedBenefit: 'Faster test writing, more consistent test quality',
    adopted: false,
  });

  // Direction 5: New capability (generic)
  directions.push({
    id: 'dir-feat-1',
    name: 'Feature: Batch Operations',
    description: 'Add batch operation support to existing commands (e.g., archive multiple)',
    category: 'feature',
    riskLevel: 3,
    affectedFiles: ['src/cli/commands/change.ts', 'src/change/manager.ts'],
    changeSummary: 'Add --all flag and batch processing to applicable commands',
    expectedBenefit: 'Improved efficiency for bulk operations',
    adopted: false,
  });

  // Filter by focus categories and limit to direction count
  const filtered = directions.filter((d) =>
    categories.includes(d.category)
  );

  return filtered.slice(0, config.directionCount);
}

/**
 * Get default categories for direction generation.
 */
function getDefaultCategories(): ExperimentCategory[] {
  return ['performance', 'robustness', 'usability', 'maintainability', 'feature'];
}

/**
 * Analyze source directory to find module names.
 */
function analyzeSourceModules(srcDir: string): string[] {
  if (!existsSync(srcDir)) return [];
  try {
    return readdirSync(srcDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name);
  } catch {
    return [];
  }
}

/**
 * Count total source files.
 */
function countSourceFiles(srcDir: string): number {
  if (!existsSync(srcDir)) return 0;
  try {
    const entries = readdirSync(srcDir, { recursive: true, withFileTypes: true })
      .filter((e) => e.isFile() && /\.(ts|js|mjs)$/.test(e.name));
    return entries.length;
  } catch {
    return 0;
  }
}

/**
 * Calculate average lines per source file.
 */
function calculateAvgFileSize(srcDir: string, fileCount: number): number {
  if (fileCount === 0) return 0;
  try {
    const files = readdirSync(srcDir, { recursive: true, withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith('.ts'))
      .slice(0, 50); // Sample first 50 files

    let totalLines = 0;
    for (const file of files) {
      try {
        const content = readFileSync(resolve(file.parentPath, file.name), 'utf8');
        totalLines += content.split('\n').length;
      } catch {
        // Skip unreadable files
      }
    }
    return files.length > 0 ? totalLines / files.length : 0;
  } catch {
    return 0;
  }
}

/**
 * Find files exceeding the line threshold.
 */
function findLargeFiles(srcDir: string, threshold: number): string[] {
  const large: string[] = [];
  try {
    const files = readdirSync(srcDir, { recursive: true, withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith('.ts'));

    for (const file of files) {
      const filePath = resolve(file.parentPath, file.name);
      try {
        const content = readFileSync(filePath, 'utf8');
        if (content.split('\n').length > threshold) {
          large.push(filePath.replace(srcDir, 'src').replace(/\\/g, '/'));
        }
      } catch {
        // Skip
      }
    }
  } catch {
    // Return empty on error
  }
  return large.slice(0, 10);
}

/**
 * Find files that contain error handling patterns.
 */
function findFilesWithErrorHandling(srcDir: string): string[] {
  const found: string[] = [];
  try {
    const files = readdirSync(srcDir, { recursive: true, withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith('.ts'))
      .slice(0, 30);

    for (const file of files) {
      const filePath = resolve(file.parentPath, file.name);
      try {
        const content = readFileSync(filePath, 'utf8');
        if (content.includes('throw new Error') || content.includes('catch (')) {
          found.push(filePath.replace(srcDir, 'src').replace(/\\/g, '/'));
        }
      } catch {
        // Skip
      }
    }
  } catch {
    // Return empty
  }
  return found.slice(0, 5);
}

/**
 * Find test files with repeated patterns.
 */
function findTestFilesWithPatterns(srcDir: string): string[] {
  const testDir = resolve(srcDir, '..', 'tests');
  if (!existsSync(testDir)) return [];
  try {
    return (readdirSync(testDir) as string[])
      .filter((f) => f.endsWith('.test.ts'))
      .map((f) => `tests/${f}`);
  } catch {
    return [];
  }
}

