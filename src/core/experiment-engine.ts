/**
 * Compare results across all arms and generate rankings.
 */
export function compareArms(
  projectRoot: string,
  experimentName: string,
): ExperimentComparison {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) throw new Error(`Experiment not found: ${experimentName}`);

  state.phase = 'comparing';

  const completedArms = state.arms.filter((a) => a.status === 'completed' && a.metrics);
  const failedArms = state.arms.filter((a) => a.status === 'failed');

  // Compute rankings
  const rankings: ExperimentRanking[] = completedArms
    .map((arm) => {
      const direction = state.directions.find((d) => d.id === arm.directionId);
      const metrics = arm.metrics!;
      const compositeScore = computeCompositeScore(metrics);
      return {
        rank: 0, // Will be set after sorting
        armId: arm.id,
        directionId: arm.directionId,
        directionName: direction?.name ?? arm.directionId,
        compositeScore,
        strengths: identifyStrengths(metrics),
        weaknesses: identifyWeaknesses(metrics),
      };
    })
    .sort((a, b) => b.compositeScore - a.compositeScore)
    .map((entry, index) => ({ ...entry, rank: index + 1 }));

  // Generate insights
  const insights = generateInsights(completedArms.map((a) => a.metrics!), state.directions);

  // Generate recommendations
  const recommendations = rankings
    .filter((r) => r.compositeScore >= 60)
    .map((r) => r.directionId);

  const comparison: ExperimentComparison = {
    generatedAt: now(),
    totalArms: state.arms.length,
    successfulArms: completedArms.length,
    failedArms: failedArms.length,
    rankings,
    insights,
    recommendations,
  };

  state.comparison = comparison;
  saveExperimentState(projectRoot, state);

  return comparison;
}

/**
 * Compute composite score from all metrics (0-100).
 */
function computeCompositeScore(metrics: ExperimentMetrics): number {
  const weights = {
    quality: 0.35,
    performance: 0.35,
    robustness: 0.30,
  };
  return Math.round(
    (metrics.qualityScore * weights.quality +
      metrics.performanceScore * weights.performance +
      metrics.robustnessScore * weights.robustness) *
      100
  );
}

/**
 * Identify strengths from metrics.
 */
function identifyStrengths(metrics: ExperimentMetrics): string[] {
  const strengths: string[] = [];
  if (metrics.evalResults.successRate >= 0.9) {
    strengths.push('High eval pass rate');
  }
  if (metrics.performanceScore >= 0.7) {
    strengths.push('Fast execution');
  }
  if (metrics.changeResults.errors.length === 0) {
    strengths.push('Clean execution');
  }
  if (metrics.changeResults.phasesCompleted >= 4) {
    strengths.push('Near-complete workflow');
  }
  return strengths;
}

/**
 * Identify weaknesses from metrics.
 */
function identifyWeaknesses(metrics: ExperimentMetrics): string[] {
  const weaknesses: string[] = [];
  if (metrics.evalResults.successRate < 0.7) {
    weaknesses.push('Low eval pass rate');
  }
  if (metrics.changeResults.failedActions > 0) {
    weaknesses.push(`${metrics.changeResults.failedActions} failed actions`);
  }
  if (metrics.changeResults.phasesCompleted < 3) {
    weaknesses.push('Incomplete workflow');
  }
  if (metrics.evalResults.totalErrors > 5) {
    weaknesses.push('High error count');
  }
  return weaknesses;
}

/**
 * Generate insights by comparing metrics across arms.
 */
function generateInsights(
  allMetrics: ExperimentMetrics[],
  directions: ExperimentDirection[],
): ExperimentInsight[] {
  const insights: ExperimentInsight[] = [];

  if (allMetrics.length === 0) return insights;

  // Performance comparison
  const perfScores = allMetrics.map((m) => m.performanceScore);
  const avgPerf = perfScores.reduce((a, b) => a + b, 0) / perfScores.length;

  if (Math.max(...perfScores) - Math.min(...perfScores) > 0.3) {
    insights.push({
      category: 'performance',
      description: `Significant performance variance detected (${Math.round(avgPerf * 100)}% avg). Consider investigating what drives the differences.`,
      relatedArms: allMetrics.map((_, i) => `arm-${i}`),
      importance: 4,
    });
  }

  // Quality comparison
  const qualityScores = allMetrics.map((m) => m.qualityScore);
  const bestQuality = Math.max(...qualityScores);
  const bestIdx = qualityScores.indexOf(bestQuality);

  if (bestQuality > 0.8) {
    insights.push({
      category: 'quality',
      description: `Arm arm-${bestIdx} shows best quality score (${Math.round(bestQuality * 100)}%) with direction: ${directions[bestIdx]?.name ?? 'unknown'}.`,
      relatedArms: [`arm-dir-${directions[bestIdx]?.id ?? bestIdx}`],
      importance: 5,
    });
  }

  // General insight
  if (allMetrics.length >= 3) {
    insights.push({
      category: 'general',
      description: `${allMetrics.length} arms completed with measurable differences. Multiple improvement vectors confirmed.`,
      relatedArms: allMetrics.map((_, i) => `arm-${i}`),
      importance: 3,
    });
  }

  return insights;
}

