/**
 * Run the demo change in a specific arm's worktree.
 */
export function runArm(
  projectRoot: string,
  experimentName: string,
  armId: string,
): ExperimentMetrics {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) throw new Error(`Experiment not found: ${experimentName}`);

  const arm = state.arms.find((a) => a.id === armId);
  if (!arm) throw new Error(`Arm not found: ${armId}`);

  arm.status = 'running';
  arm.startedAt = now();
  state.phase = 'running';
  saveExperimentState(projectRoot, state);

  try {
    // Collect eval results
    const evalResults = runEvalInWorktree(arm.worktreePath);

    // Simulate change execution metrics (in real use, an AI agent would execute the change)
    const changeResults = simulateChangeExecution(arm.worktreePath, state.demoChangeName);

    // Compute composite scores
    const qualityScore = computeQualityScore(evalResults);
    const performanceScore = computePerformanceScore(arm, evalResults);
    const robustnessScore = computeRobustnessScore(changeResults);

    const metrics: ExperimentMetrics = {
      evalResults,
      changeResults,
      qualityScore,
      performanceScore,
      robustnessScore,
      collectedAt: now(),
    };

    arm.metrics = metrics;
    arm.status = 'completed';
    arm.completedAt = now();
    saveExperimentState(projectRoot, state);

    return metrics;
  } catch (err) {
    arm.status = 'failed';
    arm.error = err instanceof Error ? err.message : String(err);
    saveExperimentState(projectRoot, state);
    throw err;
  }
}

/**
 * Run eval suite in a worktree.
 */
function runEvalInWorktree(worktreePath: string): ExperimentEvalResults {
  const startTime = Date.now();

  try {
    const report = runAllEvals(worktreePath);
    return {
      totalScenarios: report.total,
      passedScenarios: report.passed,
      failedScenarios: report.failed,
      successRate: report.total > 0 ? report.passed / report.total : 0,
      totalErrors: report.results.reduce(
        (sum, r) => sum + r.errors.length, 0
      ),
      totalWarnings: report.results.reduce(
        (sum, r) => sum + r.warnings.length, 0
      ),
      durationMs: Date.now() - startTime,
    };
  } catch {
    // If eval suite can't run, return empty results
    return {
      totalScenarios: 0,
      passedScenarios: 0,
      failedScenarios: 0,
      successRate: 0,
      totalErrors: 0,
      totalWarnings: 0,
      durationMs: Date.now() - startTime,
    };
  }
}

/**
 * Simulate change execution by checking directory structure and state.
 * ponytail: structural check only — real execution requires AI agent
 */
function simulateChangeExecution(
  worktreePath: string,
  changeName: string,
): ExperimentChangeResults {
  const startTime = Date.now();
  const changesDir = resolve(worktreePath, '.mumuspec', 'changes', changeName);

  let phasesCompleted = 0;
  let totalPhases = 5; // open, design, build, verify, archive
  const errors: string[] = [];
  const warnings: string[] = [];

  // Check for artifacts from each phase
  if (existsSync(resolve(changesDir, 'proposal.md'))) phasesCompleted++;
  if (existsSync(resolve(changesDir, 'design.md'))) phasesCompleted++;
  if (existsSync(resolve(changesDir, 'tasks.md'))) phasesCompleted++;
  if (existsSync(resolve(changesDir, 'verify.md'))) phasesCompleted++;

  // Check for archived state
  const archiveDir = resolve(worktreePath, '.mumuspec', 'changes', 'archive');
  if (existsSync(archiveDir)) {
    const archived = readdirSync(archiveDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && e.name.includes(changeName));
    if (archived.length > 0) {
      phasesCompleted = totalPhases;
    }
  }

  // Check for error indicators in audit log
  const auditPath = resolve(worktreePath, '.mumuspec', 'audit.log');
  if (existsSync(auditPath)) {
    try {
      const audit = readFileSync(auditPath, 'utf8');
      const entries = audit.split('\n').filter(Boolean);
      for (const entry of entries.slice(-20)) {
        try {
          const parsed = JSON.parse(entry);
          if (parsed.result === 'error' || parsed.result === 'failed') {
            errors.push(`${parsed.action}: ${parsed.result}`);
          }
        } catch {
          // Skip unparseable entries
        }
      }
    } catch {
      // Ignore audit read errors
    }
  }

  if (phasesCompleted === 0) {
    warnings.push(`No change artifacts found for "${changeName}"`);
  }

  return {
    changeName,
    success: phasesCompleted >= 3,
    phasesCompleted,
    totalPhases,
    totalActions: 0, // Would be populated by real execution
    failedActions: errors.length,
    durationMs: Date.now() - startTime,
    errors,
    warnings,
    verifyResult: phasesCompleted >= 4 ? 'pass' : 'pending',
  };
}

/**
 * Compute quality score from eval results.
 */
function computeQualityScore(evalResults: ExperimentEvalResults): number {
  if (evalResults.totalScenarios === 0) return 0.5;
  const successRate = evalResults.successRate;
  const errorPenalty = Math.min(evalResults.totalErrors / 10, 0.3);
  return Math.max(0, Math.min(1, successRate - errorPenalty));
}

/**
 * Compute performance score from arm execution.
 */
function computePerformanceScore(
  arm: ExperimentArm,
  evalResults: ExperimentEvalResults,
): number {
  if (!arm.startedAt || !arm.completedAt) return 0;
  const duration = new Date(arm.completedAt).getTime() - new Date(arm.startedAt).getTime();
  // Normalize: <10s = high score, >60s = low score
  const speedScore = Math.max(0, Math.min(1, 1 - duration / 60000));
  const evalSpeed = evalResults.durationMs;
  const evalSpeedScore = Math.max(0, Math.min(1, 1 - evalSpeed / 30000));
  return (speedScore + evalSpeedScore) / 2;
}

/**
 * Compute robustness score from change execution results.
 */
function computeRobustnessScore(changeResults: ExperimentChangeResults): number {
  const phaseRatio = changeResults.phasesCompleted / Math.max(changeResults.totalPhases, 1);
  const errorPenalty = Math.min(changeResults.failedActions * 0.1, 0.4);
  return Math.max(0, Math.min(1, phaseRatio - errorPenalty));
}

