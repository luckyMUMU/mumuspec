/**
 * Initialize an experiment with generated directions.
 */
export function initExperiment(
  projectRoot: string,
  input: ExperimentInitInput,
): ExperimentState {
  const experimentDir = getExperimentDir(projectRoot, input.name);
  ensureDir(experimentDir);

  // Detect current branch and commit（git() 封装：失败抛错而非静默空值）
  const originalBranch = getCurrentBranch(projectRoot);
  if (!originalBranch) {
    throw new Error('Cannot init experiment: detached HEAD or not a git repository');
  }
  const baseCommit = getHeadSha(projectRoot);
  if (!baseCommit) {
    throw new Error('Cannot init experiment: empty repository (no HEAD commit)');
  }

  // Generate directions
  const directions = generateDirections(projectRoot, input.config);

  const state: ExperimentState = {
    name: input.name,
    goal: input.goal,
    enabled: true,
    phase: 'init',
    maxMetaRounds: input.config.maxMetaRounds ?? DEFAULT_META_ROUNDS,
    currentMetaRound: 0,
    directionCount: directions.length,
    demoChangeName: input.config.demoChangeName,
    demoProjectPath: input.config.demoProjectPath,
    directions,
    arms: [],
    comparison: null,
    selectedDirections: [],
    mergedBack: false,
    originalBranch,
    baseCommit,
    createdAt: now(),
    notes: [],
  };

  saveExperimentState(projectRoot, state);

  // Audit log
  appendAuditLog(getMumuSpecDir(projectRoot), {
    actor: 'user',
    action: 'experiment.init',
    change: input.name,
    result: `success: ${directions.length} directions`,
  });

  return state;
}

/**
 * Spawn worktrees for each direction.
 */
export function spawnArms(
  projectRoot: string,
  experimentName: string,
): ExperimentArm[] {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) throw new Error(`Experiment not found: ${experimentName}`);

  state.phase = 'spawning';
  const arms: ExperimentArm[] = [];

  for (const direction of state.directions) {
    const armId = `arm-${direction.id}`;
    const branch = `experiment/${experimentName}/${direction.id}`;
    const worktreePath = resolve(
      projectRoot,
      '.mumuspec',
      '.experiment-worktrees',
      experimentName,
      direction.id
    );

    // Clean up any existing worktree/branch
    cleanupExistingWorktree(projectRoot, worktreePath, branch);

    // Create worktree
    const wtResult = spawnSync(
      'git', ['worktree', 'add', '-b', branch, worktreePath, state.baseCommit!],
      { cwd: projectRoot, stdio: 'ignore' }
    );
    if (wtResult.status !== 0) {
      throw new Error(`Failed to create worktree for ${direction.id}: ${String(wtResult.stderr ?? '')}`);
    }

    // Apply direction-specific code modifications
    applyDirectionPatch(projectRoot, worktreePath, direction);

    arms.push({
      id: armId,
      directionId: direction.id,
      worktreePath,
      branch,
      status: 'pending',
    });
  }

  state.arms = arms;
  saveExperimentState(projectRoot, state);

  return arms;
}

/**
 * Apply code modifications for a direction in its worktree.
 * ponytail: apply minimal semantic patches, not full reimplementation
 */
function applyDirectionPatch(
  _projectRoot: string,
  worktreePath: string,
  direction: ExperimentDirection,
): void {
  // Apply different patches based on direction category
  // These are minimal patches that demonstrate the improvement direction

  for (const file of direction.affectedFiles) {
    const filePath = resolve(worktreePath, file);
    if (!existsSync(filePath)) continue;

    let content = readText(filePath);
    if (!content) continue;

    // Apply a marker comment to indicate this arm's modification
    const marker = `// [experiment:${direction.id}] ${direction.name}\n`;

    // Check if already patched
    if (!content.includes(marker)) {
      content = marker + content;
      writeText(filePath, content);
    }
  }
}

/**
 * Clean up existing worktree and branch if they exist.
 */
function cleanupExistingWorktree(
  projectRoot: string,
  worktreePath: string,
  branch: string,
): void {
  // Remove worktree and branch (ignore failures — they may not exist)
  spawnSync('git', ['worktree', 'remove', worktreePath, '--force'], {
    cwd: projectRoot,
    stdio: 'ignore',
  });
  spawnSync('git', ['branch', '-D', branch], {
    cwd: projectRoot,
    stdio: 'ignore',
  });
}

