/**
 * Get the experiment directory path.
 */
function getExperimentDir(projectRoot: string, experimentName: string): string {
  return resolve(projectRoot, '.mumuspec', EXPERIMENT_DIR, experimentName);
}

/**
 * Save experiment state to disk.
 */
function saveExperimentState(projectRoot: string, state: ExperimentState): void {
  const dir = getExperimentDir(projectRoot, state.name);
  ensureDir(dir);
  writeYaml(resolve(dir, 'experiment.yaml'), state);
}

/**
 * Load experiment state from disk.
 */
export function loadExperimentState(
  projectRoot: string,
  experimentName: string,
): ExperimentState | null {
  const dir = getExperimentDir(projectRoot, experimentName);
  const filePath = resolve(dir, 'experiment.yaml');
  if (!existsSync(filePath)) return null;
  return readYaml<ExperimentState>(filePath) ?? null;
}

/**
 * Get experiment status summary.
 */
export function getExperimentStatus(
  projectRoot: string,
  experimentName: string,
): ExperimentStatusSummary | null {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state || !state.enabled) return null;

  const completed = state.arms.filter((a) => a.status === 'completed').length;
  const failed = state.arms.filter((a) => a.status === 'failed').length;

  return {
    name: state.name,
    phase: state.phase,
    currentMetaRound: state.currentMetaRound,
    maxMetaRounds: state.maxMetaRounds,
    directionCount: state.directions.length,
    armsTotal: state.arms.length,
    armsCompleted: completed,
    armsFailed: failed,
    comparisonReady: !!state.comparison,
    selectedCount: state.selectedDirections.length,
    mergedBack: state.mergedBack,
  };
}

/**
 * List all experiments in the project.
 */
export function listExperiments(projectRoot: string): ExperimentStatusSummary[] {
  const dir = resolve(projectRoot, '.mumuspec', EXPERIMENT_DIR);
  if (!existsSync(dir)) return [];

  const entries = readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory());

  return entries
    .map((e) => getExperimentStatus(projectRoot, e.name))
    .filter((s): s is ExperimentStatusSummary => s !== null);
}

/**
 * Clean up experiment worktrees.
 */
export function cleanupExperiment(
  projectRoot: string,
  experimentName: string,
  options: { dryRun?: boolean } = {},
): { cleaned: string[]; errors: string[] } {
  const state = loadExperimentState(projectRoot, experimentName);
  if (!state) return { cleaned: [], errors: [`Experiment not found: ${experimentName}`] };

  const cleaned: string[] = [];
  const errors: string[] = [];

  for (const arm of state.arms) {
    if (existsSync(arm.worktreePath)) {
      if (options.dryRun) {
        cleaned.push(arm.worktreePath);
      } else {
        const rmResult = spawnSync('git', ['worktree', 'remove', arm.worktreePath, '--force'], {
          cwd: projectRoot,
          stdio: 'ignore',
        });
        if (rmResult.status === 0) {
          cleaned.push(arm.worktreePath);
        } else {
          errors.push(`Failed to remove ${arm.worktreePath}: git worktree remove failed (status ${rmResult.status})`);
        }
      }
    }
  }

  return { cleaned, errors };
}

